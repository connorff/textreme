function escapeAppleScriptString(str: string): string {
  // Replace backslashes first, then quotes
  return str.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

// Helper function to execute AppleScript using shell command with timeout
async function executeAppleScript(
  script: string,
  timeoutMs: number = 10000
): Promise<void> {
  // Escape the script for shell: replace single quotes with '\'' and wrap in single quotes
  // This ensures the script is safely passed to the shell
  const escapedScript = script.replace(/'/g, "'\\''");
  // Use printf to pipe the script to osascript, which handles newlines and special chars better
  const command = `printf '%s\n' '${escapedScript}' | osascript`;

  // Create a promise that times out
  const timeoutPromise = new Promise<never>((_, reject) => {
    setTimeout(
      () =>
        reject(
          new Error(`AppleScript execution timed out after ${timeoutMs}ms`)
        ),
      timeoutMs
    );
  });

  try {
    const { stdout, stderr } = await Promise.race([
      execAsync(command),
      timeoutPromise,
    ]);

    // Some AppleScript errors are expected (like Messages app warnings)
    // Only throw if it's a real error
    if (
      stderr &&
      !stderr.includes("Messages") &&
      !stderr.includes("execution error")
    ) {
      throw new Error(stderr);
    }
  } catch (error) {
    console.error("AppleScript execution error:", error);
    throw error;
  }
}

// Helper function to mark conversation as read by clicking on it in Messages
async function markConversationAsReadViaClick(
  recipient: string
): Promise<void> {
  try {
    const escapedRecipient = escapeAppleScriptString(recipient);

    const appleScript = `
set recipient to "${escapedRecipient}"

set h to ""

-- Try to find contact by name first
try
  tell application "Contacts"
    set p to first person whose name is recipient
    if (count of phones of p) > 0 then
      set h to value of first phone of p
    else if (count of emails of p) > 0 then
      set h to value of first email of p
    end if
  end tell
on error
  -- If not found as contact name, assume recipient is already phone/email
  set h to recipient
end try

if h is "" then
  set h to recipient
end if

-- Activate Messages and click on the conversation to mark it as read
tell application "Messages"
  activate
  delay 0.5
end tell

tell application "System Events"
  tell process "Messages"
    -- Wait for Messages window to be ready
    repeat until exists window 1
      delay 0.1
    end repeat
    
    -- Try to find and click the conversation in the sidebar
    try
      -- Look for the conversation row that contains the recipient identifier
      set conversationRows to rows of table 1 of scroll area 1 of splitter group 1 of window 1
      repeat with aRow in conversationRows
        try
          set rowText to value of static text 1 of aRow
          if rowText contains h or rowText contains recipient then
            -- Click on the row to open the conversation and mark as read
            click aRow
            delay 0.2
            exit repeat
          end if
        end try
      end repeat
    on error errMsg
      -- If UI structure is different, try alternative approach
      log "Could not find conversation row: " & errMsg
    end try
  end tell
end tell

-- Hide Messages app again
tell application "System Events"
  set visible of process "Messages" to false
end tell

delay 0.3
`.trim();

    await executeAppleScript(appleScript);
  } catch (error: any) {
    console.error("Error marking conversation as read via click:", error);
    // Don't throw - this is a best-effort operation
  }
}

// AppleScript execution handler
ipcMain.handle(
  "send-imessage",
  async (_event, recipient: string, messageText: string) => {
    try {
      if (!recipient || recipient.trim() === "") {
        return {
          success: false,
          error: "Recipient is empty",
        };
      }

      if (!messageText || messageText.trim() === "") {
        return {
          success: false,
          error: "Message text is empty",
        };
      }

      // Escape strings for AppleScript
      const escapedRecipient = escapeAppleScriptString(recipient);
      const escapedMessage = escapeAppleScriptString(messageText);

      // Build AppleScript with proper escaping
      // Use AppleScript's quoted form for safer string handling

      const appleScript = `
set recipient to "${escapedRecipient}"
set messageText to "${escapedMessage}"

set h to ""

-- Try to find contact by name first
try
  tell application "Contacts"
    set p to first person whose name is recipient
    if (count of phones of p) > 0 then
      set h to value of first phone of p
    else if (count of emails of p) > 0 then
      set h to value of first email of p
    end if
  end tell
on error
  -- If not found as contact name, assume recipient is already phone/email
  set h to recipient
end try

if h is "" then
  error "Recipient has no phone or email in Contacts."
end if

-- Ensure Messages is running and responsive
tell application "Messages"
  -- Briefly activate to ensure it's responsive
  activate
  delay 0.1
end tell

-- Hide Messages immediately
tell application "System Events"
  set visible of process "Messages" to false
end tell

-- Send message
tell application "Messages"
  set targetService to 1st service whose service type = iMessage
  set targetBuddy to buddy h of targetService
  send messageText to targetBuddy
end tell

-- Small delay to ensure message is sent
delay 0.2
`.trim();

      // Execute using spawn with stdin for reliable script execution
      await executeAppleScript(appleScript, 5000); // 5 second timeout

      // After successfully sending, mark the conversation as read (non-blocking)
      markConversationAsReadViaClick(recipient).catch(() => {
        // Silently fail - this is non-critical
      });

      return {
        success: true,
        message: "Message sent successfully!",
      };
    } catch (error) {
      console.error("Error sending iMessage:", error);
      return {
        success: false,
        error:
          error instanceof Error ? error.message : "Unknown error occurred",
      };
    }
  }
);
