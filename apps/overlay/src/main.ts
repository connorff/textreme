let cachedCliPath: string | null = null;
let cliBuildPromise: Promise<void> | null = null;

function resolveCliBinaryPath(): string {
  if (cachedCliPath) {
    return cachedCliPath;
  }

  if (CLI_ENV_OVERRIDE && CLI_ENV_OVERRIDE.length > 0) {
    cachedCliPath = CLI_ENV_OVERRIDE;
    return cachedCliPath;
  }

  if (app.isPackaged) {
    cachedCliPath = path.join(process.resourcesPath, CLI_BASENAME);
  } else {
    cachedCliPath = CLI_DEV_BINARY;
  }

  return cachedCliPath;
}

function ensureCliExists(cliPath: string): boolean {
  return fs.existsSync(cliPath);
}

async function buildCliBinary(): Promise<void> {
  console.log("[cli] Building imessage_query (cargo build --release)...");

  await new Promise<void>((resolve, reject) => {
    const child = spawn("cargo", ["build", "--release"], {
      cwd: CLI_PROJECT_DIR,
      stdio: "inherit",
    });

    child.on("error", (error) => {
      reject(error);
    });

    child.on("close", (code) => {
      if (code === 0) {
        resolve();
      } else {
        reject(new Error(`cargo build exited with code ${code ?? "unknown"}`));
      }
    });
  });
}

async function ensureCliReady(): Promise<string> {
  const cliPath = resolveCliBinaryPath();

  if (ensureCliExists(cliPath)) {
    return cliPath;
  }

  if (app.isPackaged) {
    throw new Error(
      `imessage_query binary missing at ${cliPath}. Please reinstall the application.`
    );
  }

  if (SKIP_CLI_BUILD) {
    throw new Error(
      `imessage_query binary not found at ${cliPath} and automatic build disabled (IMESSAGE_QUERY_SKIP_BUILD=1).`
    );
  }

  if (!cliBuildPromise) {
    cliBuildPromise = buildCliBinary().finally(() => {
      cliBuildPromise = null;
    });
  }

  await cliBuildPromise;

  if (!ensureCliExists(cliPath)) {
    throw new Error(
      `imessage_query binary still missing at ${cliPath} after build attempt.`
    );
  }

  return cliPath;
}

async function runImessageCli<T>(
  args: string[],
  schema: z.ZodType<T>
): Promise<T> {
  const cliPath = await ensureCliReady();

  return await new Promise<T>((resolve, reject) => {
    const child = spawn(cliPath, args, {
      stdio: ["ignore", "pipe", "pipe"],
    });

    let stdout = "";
    let stderr = "";

    child.stdout.on("data", (chunk) => {
      stdout += chunk.toString();
    });

    child.stderr.on("data", (chunk) => {
      stderr += chunk.toString();
    });

    child.on("error", (error) => {
      reject(error);
    });

    child.on("close", (code) => {
      if (code !== 0) {
        const message = stderr.trim() || `exit code ${code}`;
        reject(new Error(`imessage_query failed: ${message}`));
        return;
      }

      try {
        const parsed = schema.parse(JSON.parse(stdout));
        resolve(parsed);
      } catch (error: any) {
        reject(
          new Error(
            `Failed to parse imessage_query output: ${error.message}
stdout: ${stdout}
stderr: ${stderr}`
          )
        );
      }
    });
  });
}

