async function lookupConversationDisplayName(
  chatGuid: string
): Promise<string | undefined> {
  const metadata = await fetchConversationMetadata(chatGuid);
  if (!metadata) {
    return undefined;
  }

  if (metadata.display_name && metadata.display_name.trim().length > 0) {
    return metadata.display_name;
  }

  const participants = metadata.participants ?? [];
  const phoneNumbers = participants.filter(
    (identifier) => !identifier.includes("@") && isValidPhoneNumber(identifier)
  );

  const numbersToLoad = phoneNumbers.filter((num) => !contactCache.has(num));
  if (numbersToLoad.length > 0) {
    await loadContactsForNumbers(numbersToLoad);
  }

  for (const identifier of participants) {
    const name = lookupContactName(identifier);
    if (name) {
      return name;
    }
  }

  if (metadata.chat_identifier) {
    return metadata.chat_identifier;
  }

  return participants[0];
}

